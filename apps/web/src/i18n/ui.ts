export type UiKey = keyof (typeof ui)['en'];

/**
 * Translator for one language, falling back to English for a missing string.
 *
 * {placeholders} are filled from the second argument. Swedish word order is not
 * English word order — "Basket i Stockholm" against "Basketball in Stockholm"
 * is the easy case, but several strings move the number to the other end of the
 * sentence entirely, which string concatenation cannot express.
 */
export function useTranslations(lang: Lang) {
  return function t(key: UiKey, params?: Record<string, string | number>): string {
    const raw = (ui[lang] as Record<string, string>)[key] ?? ui.en[key] ?? key;
    if (!params) return raw;
    return raw.replace(/{([a-zA-Z0-9_]+)}/g, (whole, name) =>
      name in params ? String(params[name]) : whole,
    );
  };
}

/** The same path in the other language. Used by the header's EN · SV switch. */
export function localePath(path: string, lang: Lang): string {
  const bare = path === '/sv' ? '/' : path.startsWith('/sv/') ? path.slice(3) : path;
  if (lang === 'en') return bare;
  return bare === '/' ? '/sv/' : `/sv${bare}`;
}
